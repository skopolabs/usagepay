import { OFFLINE_FIXTURE_CHANNEL_ID, buildGoldenSession, fixtureNonce, type GoldenSession } from './golden.js';
import { TEST_ONLY_METER_KEY, TEST_ONLY_PAYER_KEY, TEST_ONLY_UNTRUSTED_METER_KEY } from './test-keys.js';

/** JCS inputs whose canonical form is fixed by RFC 8785 (§3.2.2, §3.2.3) or by UsagePay rules. */
export const JCS_VECTOR_INPUTS: ReadonlyArray<{ id: string; input: unknown }> = [
  { id: 'key-order-nested', input: { b: '2', a: '1', c: { z: true, y: null, x: [3, 2, 1] } } },
  {
    id: 'rfc8785-property-sorting',
    input: {
      '€': 'Euro Sign',
      '\r': 'Carriage Return',
      'דּ': 'Hebrew Letter Dalet With Dagesh',
      '1': 'One',
      '😀': 'Emoji: Grinning Face',
      '\u0080': 'Control',
      'ö': 'Latin Small Letter O With Diaeresis',
    },
  },
  {
    id: 'rfc8785-string-escaping',
    input: { string: String.fromCharCode(0x20ac, 0x24, 0x0f, 0x0a, 0x41, 0x27, 0x42, 0x22, 0x5c, 0x5c, 0x22, 0x2f) },
  },
  { id: 'safe-integers', input: { values: [0, -1, 1, 7, 9007199254740991, -9007199254740991] } },
  { id: 'decimal-strings-not-numbers', input: { amount: '3000000', energyWh: '750' } },
];

/**
 * Deterministic test vectors for module owners. Excludes every value derived from a commitment signature: the
 * ack preimage vector uses a fixed placeholder commitment digest so no signed-commitment output is committed.
 */
export function computeVectors(golden: GoldenSession = buildGoldenSession()) {
  const { versionDigest: _excluded, ...tariffFields } = golden.tariff;
  const placeholderCommitmentDigest = sha256Hex(utf8Bytes('usagepay.vector.placeholder-commitment-digest'));
  const ackVectorUnsigned = {
    schema: 'usagepay.payer-ack.v1' as const,
    sessionId: golden.inputs.session.sessionId,
    network: NETWORK,
    channelId: OFFLINE_FIXTURE_CHANNEL_ID,
    evidenceDigest: golden.charges[0]!.evidenceDigest,
    commitmentDigest: placeholderCommitmentDigest,
    approvedCumulativeBaseUnits: golden.charges[0]!.cumulativeChargeBaseUnits,
    nonce: fixtureNonce(golden.inputs.session.sessionId, golden.readings[0]!.readingId),
    payerKey: TEST_ONLY_PAYER_KEY.accountId,
  };
  const ackPreimage = payerAckSigningMessage(ackVectorUnsigned);

  return {
    schema: 'usagepay.fixture-vectors.v1',
    contractsVersion: CONTRACTS_VERSION,
    evidenceClass: 'OFFLINE_FIXTURE',
    notice:
      'Generated by `pnpm fixtures:generate` from committed inputs and TEST-ONLY keys derived from public labels. ' +
      'Simulated meter data only; contains no native MPP commitment, no Testnet receipt and no private key.',
    testOnlyPublicKeys: {
      meter: { keyId: golden.inputs.meter.signerKeyId, label: TEST_ONLY_METER_KEY.label, publicKeyHex: bytesToHex(TEST_ONLY_METER_KEY.publicKey) },
      untrustedMeter: { label: TEST_ONLY_UNTRUSTED_METER_KEY.label, publicKeyHex: bytesToHex(TEST_ONLY_UNTRUSTED_METER_KEY.publicKey) },
      offlinePayer: { label: TEST_ONLY_PAYER_KEY.label, accountId: TEST_ONLY_PAYER_KEY.accountId },
    },
    offlineChannelId: OFFLINE_FIXTURE_CHANNEL_ID,
    jcs: JCS_VECTOR_INPUTS.map(({ id, input }) => ({ id, input, canonical: canonicalize(input), sha256: jcsDigest(input) })),
    tariff: { canonicalPreimage: canonicalize(tariffFields), versionDigest: golden.tariff.versionDigest },
    readings: golden.readings.map((reading, index) => {
      const charge = golden.charges[index]!;
      return {
        readingId: reading.readingId,
        rawPayloadUtf8: new TextDecoder().decode(base64ToBytes(reading.rawPayloadB64)),
        rawPayloadSha256: computeRawPayloadDigest(reading.rawPayloadB64),
        meterSignatureB64: reading.signatureB64,
        readingDigest: charge.readingDigest,
        deltaWh: reading.deltaWh,
        cumulativeWh: charge.cumulativeWh,
        cumulativeChargeBaseUnits: charge.cumulativeChargeBaseUnits,
        deltaChargeBaseUnits: charge.deltaChargeBaseUnits,
        evidenceDigest: charge.evidenceDigest,
      };
    }),
    payerAckPreimage: {
      domain: PAYER_ACK_DOMAIN,
      ackWithoutSignature: ackVectorUnsigned,
      preimageUtf8: new TextDecoder().decode(ackPreimage),
      preimageSha256: sha256Hex(ackPreimage),
    },
  };
}

export type FixtureVectors = ReturnType<typeof computeVectors>;

/** Stable on-disk serialization (2-space JSON, trailing newline). */
export function serializeVectors(vectors: FixtureVectors): string {
  return `${JSON.stringify(vectors, null, 2)}\n`;
}
